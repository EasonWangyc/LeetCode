/*
91. 解码方法

一条包含字母 A-Z 的消息通过以下映射进行了 编码 ：

"1" -> 'A'

"2" -> 'B'

...

"25" -> 'Y'

"26" -> 'Z'

然而，在 解码 已编码的消息时，你意识到有许多不同的方式来解码，因为有些编码被包含在其它编码当中（"2" 和 "5" 与 "25"）。

例如，"11106" 可以映射为：

"AAJF" ，将消息分组为 (1, 1, 10, 6)
"KJF" ，将消息分组为 (11, 10, 6)
消息不能分组为  (1, 11, 06) ，因为 "06" 不是一个合法编码（只有 "6" 是合法的）。
注意，可能存在无法解码的字符串。

给你一个只含数字的 非空 字符串 s ，请计算并返回 解码 方法的 总数 。如果没有合法的方式解码整个字符串，返回 0。

题目数据保证答案肯定是一个 32 位 的整数。
*/
#include <bits/stdc++.h>
using namespace std;

int numDecodings(string s) {
    int n = s.length();
    if(n == 0 || s[0] == '0') return 0;
    // dp[i]表示s[0, ..., i-1]的解码个数
    vector<int> dp(n + 1, 0);
    dp[0] = 1;
    dp[1] = 1;
    // 分类讨论s[i-1]
    // 单独解码一位，s[i-1]不能等于0，合法的情况下dp[i]=dp[i-1]
    // 合并解码两位，先合并判断合法，合法条件为[10, 26]，合法情况下，dp[i]=dp[i-2]
    for(int i = 2; i <= n; i++) {
        if(s[i - 1] != '0') dp[i] += dp[i - 1];
        int twoDigit = (s[i - 2] - '0') * 10 + (s[i - 1] - '0');
        if(twoDigit <= 26 && twoDigit >= 10) dp[i] += dp[i - 2];
    }
    return dp[n];
    // 优化是用两个变量滚动即可
}

int main() {
    cout << numDecodings("226") << " " << numDecodings("06") << " " << numDecodings("12") << "\n";
    return 0;
}